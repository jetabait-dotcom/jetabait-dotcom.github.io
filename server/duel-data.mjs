// A card can be taken only after every blocker has gone.
function layout(rows){const out=[];rows.forEach((xs,y)=>xs.forEach(x=>out.push({x,y,faceUp:y%2===0,covers:[]})));for(const item of out)item.covers=out.flatMap((other,index)=>other.y===item.y+1&&Math.abs(other.x-item.x)<1?[index]:[]);return out;}
